"""Turn results/*.jsonl into results/summary.md (tables) and results/*.png (curves)."""
import json, re
from collections import defaultdict
from pathlib import Path
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

R = Path("results")
rows = [json.loads(l) for l in (R / "results.jsonl").read_text().splitlines() if l.strip()]
KEY = {"cls": "top1", "seg": "dice_fg", "det": "mAP"}
NAME = {"cls": "CIFAR-10 top-1", "seg": "MVTec defect Dice", "det": "NEU-DET mAP@[.5:.95]"}


def label(r):
    s = r["source"]
    kind = "SimCLR" if s.startswith("simclr") else "MAE" if s.startswith("mae") else s
    return f"{r['backbone']} · {kind}"


main_rows = [r for r in rows if not r["source"].endswith("_e30")]
out = ["# Results", "", "All runs at 96×96 px on one Colab T4. Generated by `scripts/plot_results.py`.", ""]

# headline: probe and full fine-tune at 100% labels
out += ["## Headline (100 % labels)", "", "| backbone · pre-training | task | linear probe | full fine-tune |",
        "|---|---|---|---|"]
agg = defaultdict(dict)
for r in main_rows:
    if r["label_frac"] == 1.0 and KEY[r["task"]] in r:
        head = r.get("det_head") or ""
        t = NAME[r["task"]] + (" (DETR head)" if head == "detr" else "")
        agg[(label(r), t)][r["mode"]] = r[KEY[r["task"]]]
fmt = lambda v: "–" if v is None else f"{v:.3f}"
for (name, t), d in sorted(agg.items(), key=lambda kv: (kv[0][1], kv[0][0])):
    out.append(f"| {name} | {t} | {fmt(d.get('probe'))} | {fmt(d.get('full'))} |")

# data efficiency
out += ["", "## Data efficiency (full fine-tune)", ""]
for task, key in KEY.items():
    groups = defaultdict(dict)
    for r in main_rows:
        if r["task"] == task and r["mode"] == "full" and key in r and not r.get("det_head"):
            groups[label(r)][r["label_frac"]] = r[key]
    fracs = sorted({f for g in groups.values() for f in g})
    if len(fracs) < 2:
        continue
    out += [f"**{NAME[task]}**", "", "| backbone · pre-training | " + " | ".join(f"{f:g}" for f in fracs) + " |",
            "|---|" + "---|" * len(fracs)]
    plt.figure(figsize=(6, 4))
    for name, pts in sorted(groups.items()):
        out.append(f"| {name} | " + " | ".join(fmt(pts.get(f)) for f in fracs) + " |")
        xs = sorted(pts)
        plt.plot(xs, [pts[x] for x in xs], marker="o", label=name)
    out += ["", f"![](data_eff_{task}.png)", ""]
    plt.xscale("log"); plt.xlabel("fraction of labels"); plt.ylabel(key); plt.title(f"{NAME[task]}: data efficiency")
    plt.legend(fontsize=8); plt.grid(alpha=0.3); plt.tight_layout()
    plt.savefig(R / f"data_eff_{task}.png", dpi=150); plt.close()

# MAE mask-ratio ablation (30-epoch runs, CIFAR-10 linear probe)
abl = sorted((int(re.search(r"_m(\d+)_e30", r["source"]).group(1)), r["top1"]) for r in rows
             if r["source"].endswith("_e30") and r["task"] == "cls" and r["mode"] == "probe")
if abl:
    out += ["## MAE mask-ratio ablation (30 epochs, CIFAR-10 linear probe)", "", "| mask ratio | top-1 |", "|---|---|"]
    out += [f"| {m} % | {v:.3f} |" for m, v in abl] + ["", "![](mae_mask_ratio.png)", ""]
    plt.figure(figsize=(5, 3.5))
    plt.plot(*zip(*abl), marker="o"); plt.xlabel("mask ratio (%)"); plt.ylabel("linear-probe top-1")
    plt.title("MAE mask-ratio ablation"); plt.grid(alpha=0.3); plt.tight_layout()
    plt.savefig(R / "mae_mask_ratio.png", dpi=150); plt.close()

# deployment
ex = R / "export.jsonl"
if ex.exists():
    erows = [json.loads(l) for l in ex.read_text().splitlines() if l.strip()]
    keys = [k for k in ("file", "provider", "latency_ms", "throughput_img_s", "size_mb") if any(k in e for e in erows)]
    out += ["## Deployment (batch 8, 96 px)", "", "| backbone | " + " | ".join(keys) + " |",
            "|---|" + "---|" * len(keys)]
    for e in erows:
        out.append(f"| {e['backbone']} | " + " | ".join(
            f"{e[k]:.2f}" if isinstance(e.get(k), float) else str(e.get(k, "–")) for k in keys) + " |")

(R / "summary.md").write_text("\n".join(out) + "\n", encoding="utf-8")
print("\n".join(out))
